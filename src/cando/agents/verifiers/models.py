"""Data models for verifier results."""

from typing import Any

from pydantic import BaseModel, Field


class WorkerResult(BaseModel):
    """Result of worker layout compliance verification."""

    compliant: bool = Field(
        description=(
            "True if the layout is fully compliant with all rules; "
            "false otherwise."
        )
    )
    score: float = Field(
        description=(
            "Compliance score in [0.0, 1.0]. "
            "1.0 only if fully compliant; otherwise in [0.0, 0.99] "
            "based on the number and severity of violations."
        )
    )
    feedback: str = Field(
        description=(
            "Deterministic report generated by the verifier. Contains clear "
            "feedback to be read by a planning agent for refinement actions."
        )
    )

    raw_data: dict[str, Any] = Field(
        default_factory=dict,
        description=(
            "Raw computational data from verifier tools for this worker "
            "(not populated by LLMs). Keys are tool or output identifiers "
            "for this worker (e.g., 'orientation_analysis'), values are "
            "dictionaries containing raw tool outputs (e.g., groups, "
            "routes, geometric analysis)."
        ),
        exclude=True,
    )

    def to_string(self) -> str:
        """Converts this worker's result to a formatted string.

        Returns:
            str: Formatted string with the worker's compliance status, score,
                and feedback.
        """
        return (
            f"Compliant: {self.compliant}\n"
            f"Score: {self.score:.4f}\n"
            f"Feedback: {self.feedback}"
        )


class Feedback(BaseModel):
    assembly: WorkerResult = Field(
        description=("Feedback about assembly-related issues.")
    )

    hard_constraints: WorkerResult = Field(
        description=("Feedback about hard-constraints-related issues.")
    )

    orientation: WorkerResult = Field(
        description=("Feedback about orientation-related issues.")
    )

    proximity: WorkerResult = Field(
        description=("Feedback about proximity-related issues.")
    )

    flow: WorkerResult = Field(
        description=("Feedback about flow-related issues.")
    )


class VerifierResult(BaseModel):
    """Result of overall layout compliance verification."""

    valid: bool = Field(
        default=False,
        description=(
            "True if hard_constraints and flow are both fully compliant "
            "(no geometric violations and all required routes feasible). "
            "A valid layout satisfies all structural requirements and gates "
            "the 0.5 validity bonus in the overall score formula."
        ),
    )
    compliant: bool = Field(
        description=(
            "True if the layout is fully compliant with ALL rules across "
            "all workers (hard_constraints, flow, assembly, orientation, "
            "proximity); false otherwise."
        )
    )
    score: float = Field(
        description=(
            "Compliance score in [0.0, 1.0] computed as: "
            "valid * 0.5 + 0.5 * (proximity + orientation + assembly) / 3. "
            "1.0 only if fully compliant; otherwise in [0.0, 0.99]."
        )
    )
    feedback: Feedback = Field(
        description=(
            "Deterministic report generated by the verifier. Contains clear "
            "feedback to be read by a planning agent for refinement actions."
        )
    )
    raw_data: dict[str, Any] = Field(
        default_factory=dict,
        description=(
            "Raw computational data from verifier tools (not populated by "
            "LLMs). Keys are worker names (e.g., 'assembly', 'flow'), "
            "values are dictionaries containing raw tool outputs (e.g., "
            "groups, routes, geometric analysis)."
        ),
        exclude=True,
    )
